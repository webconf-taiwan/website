/**
 * 把 key 陣列展開成面板要的欄位定義。查不到的 key 直接略過 ——
 * 元件寫錯字不該讓整個面板炸掉。
 *
 * @param {string[]} keys
 * @returns {Array<{key: string, label: string, min: number, max: number, step: number, help: string}>}
 */
export function particleToolFields (keys) {
  return (keys || [])
    .filter(k => PARTICLE_TOOL_FIELDS[k])
    .map(k => ({ key: k, ...PARTICLE_TOOL_FIELDS[k] }))
}
